"""Logger interface for the PhotonIDE application.

Provides severity-specific methods and coordinates logging initialization
and message handling.
"""

from . import config
from . import handlers
from .formatters import get_file_name, get_timestamp

class Logger:
    """Log messages associated with an application component.

    The first instance initializes the shared logging system. Subsequent
    instances reuse the existing configuration and output destinations.

    Args:
        name: Name of the application component associated with this logger.
    """

    def __init__(self, name: str) -> None:
        """Create a logger and initialize the shared logging system if needed."""
        self.name = name

        if config.logger_initialized:
            return

        config.logger_initialized = True
        handlers.initialize_logging(self)

    def get_timestamp(self) -> str:
        """Return the current local date and time."""
        return get_timestamp()

    def get_file_name(self) -> str:
        """Generate a log filename based on the current local time."""
        return get_file_name()

    def _print_internal_error(self, message: str) -> None:
        """Print an internal logging error directly to the console.

        Args:
            message: Description of the internal logging error.
        """
        handlers.print_internal_error(message)

    def _log_message(
        self,
        name: str,
        message: str,
        level: str = "info",
    ) -> None:
        """Delegate message formatting and output to the logging handlers.

        Args:
            name: Name of the component generating the message.
            message: Content of the message to record.
            level: Severity level of the message. Defaults to ``info``.
        """
        handlers.log_message(self, name, message, level)

    def _log_internal(
        self,
        message: str,
        level: str = "info",
    ) -> None:
        """Record a message generated by the logging system itself.

        Internal messages use ``Logging`` as their component name.

        Args:
            message: Internal status or diagnostic message.
            level: Severity level of the message. Defaults to ``info``.
        """
        self._log_message("Logging", message, level)

    def log(self, message: str, level: str = "info") -> None:
        """Record a message using this logger's component name.

        Args:
            message: Content of the message to record.
            level: Severity level of the message. Defaults to ``info``.
        """
        self._log_message(self.name, message, level)

    def debug(self, message: str) -> None:
        """Record a diagnostic message."""
        self.log(message, "debug")

    def info(self, message: str) -> None:
        """Record an informational message."""
        self.log(message, "info")

    def warning(self, message: str) -> None:
        """Record a warning about a potentially problematic condition."""
        self.log(message, "warning")

    def error(self, message: str) -> None:
        """Record an error encountered during application execution."""
        self.log(message, "error")

    def critical(self, message: str) -> None:
        """Record a critical error requiring immediate attention."""
        self.log(message, "critical")